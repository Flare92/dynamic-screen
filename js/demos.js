const BASE = 'media/ex/';
/** { a, b, nota } con gli indirizzi delle due foto, oppure null se l'esercizio non ha foto */
export function demoFor(id) {
  const d = DEMOS[id];
  return d ? { a: `${BASE}${d.f}_0.webp`, b: `${BASE}${d.f}_1.webp`, nota: d.nota || '' } : null;
}
export const hasDemo = (id) => !!DEMOS[id];

